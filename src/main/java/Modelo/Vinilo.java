package Modelo;

public class Vinilo {
    private String artista;
    private String nombre;
    private String ano;

    /**
     * Constructor
     * @param artista es el músico que toca.
     * @param nombre es el nombre del álbum/disco.
     * @param ano año de publicaación.
     */
    public Vinilo(String artista, String nombre, String ano) {
        this.artista = artista;
        this.nombre = nombre;
        this.ano = ano;
    }

}
